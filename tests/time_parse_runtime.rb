def outcome(fmt)
  fmt.call(yield)
rescue ArgumentError
  ArgumentError
end

failures = CASES.flat_map do |input, zone, parse|
  [
    ["zone_parse", zone, outcome(fmt) { ActiveSupport.zone_parse(input) }],
    ["parse_time", parse, outcome(fmt) { ActiveSupport.parse_time(input) }],
  ].filter_map do |name, want, got|
    "#{name}(#{input.inspect}): want #{want.inspect}, got #{got.inspect}" unless want == got
  end
end

begin
  ActiveSupport.zone_parse(nil)
  failures << "zone_parse(nil): want TypeError, got no raise"
rescue TypeError
end

puts "cases #{CASES.size}"
puts failures
puts "ALL OK" if failures.empty?
exit(failures.empty? ? 0 : 1)
